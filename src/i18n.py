class Translator:
    """Simple translator for TUI strings and column names."""

    def __init__(self, lang: str = "en"):
        self.lang = lang if lang in _TRANSLATIONS else "en"

    def t(self, key: str, **kwargs) -> str:
        """Translate a simple key."""
        text = _TRANSLATIONS.get(self.lang, _TRANSLATIONS["en"]).get(key, key)
        if kwargs:
            return text.format(**kwargs)
        return text

    def col(self, name: str) -> str:
        """Translate a DataFrame column name."""
        return _COLUMN_MAP.get(self.lang, _COLUMN_MAP["en"]).get(name, name)


def get_translator(lang: str = "en") -> Translator:
    return Translator(lang)
